CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE documents (
  project_id         TEXT PRIMARY KEY,
  owner_id           TEXT,
  document_id        TEXT NOT NULL,
  title              TEXT NOT NULL,
  template           JSONB NOT NULL DEFAULT '{}'::jsonb,
  blocks             JSONB NOT NULL,
  preference_entries JSONB NOT NULL,
  tombstones         JSONB NOT NULL,
  created_at         TIMESTAMPTZ NOT NULL,
  updated_at         TIMESTAMPTZ NOT NULL
);

CREATE TABLE document_versions (
  project_id        TEXT NOT NULL REFERENCES documents(project_id) ON DELETE CASCADE,
  owner_id          TEXT,
  version_no        INTEGER NOT NULL,
  "trigger"         TEXT NOT NULL,
  summary           TEXT NOT NULL,
  changed_block_ids TEXT[] NOT NULL,
  snapshot          JSONB NOT NULL,
  created_at        TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (project_id, version_no)
);

CREATE TABLE rounds (
  round_id         TEXT PRIMARY KEY,
  project_id       TEXT NOT NULL,
  owner_id         TEXT,
  step             TEXT NOT NULL,
  waiting_on       TEXT NOT NULL,
  payload          JSONB NOT NULL,
  created_at       TIMESTAMPTZ NOT NULL,
  updated_at       TIMESTAMPTZ NOT NULL,
  lease_owner      TEXT,
  lease_expires_at BIGINT,
  lease_token      INTEGER NOT NULL DEFAULT 0,
  seq              BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_rounds_project ON rounds(project_id, created_at);

CREATE TABLE round_skips (
  round_id     TEXT NOT NULL,
  owner_id     TEXT NOT NULL,
  seat_id      TEXT NOT NULL,
  pass_index   INTEGER NOT NULL,
  reason       TEXT NOT NULL,
  source       TEXT NOT NULL,
  requested_at BIGINT NOT NULL,
  seq          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY (round_id, seat_id)
);
CREATE INDEX idx_round_skips_owner ON round_skips(owner_id, round_id);

CREATE TABLE templates (
  template_id TEXT PRIMARY KEY,
  owner_id    TEXT,
  title       TEXT NOT NULL,
  spec        JSONB NOT NULL,
  builtin     BOOLEAN NOT NULL DEFAULT false,
  created_at  TIMESTAMPTZ NOT NULL,
  updated_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE evidence_ledgers (
  project_id TEXT PRIMARY KEY REFERENCES documents(project_id) ON DELETE CASCADE,
  owner_id   TEXT,
  payload    JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE materials (
  material_id    TEXT PRIMARY KEY,
  project_id     TEXT NOT NULL,
  owner_id       TEXT,
  origin         TEXT NOT NULL,
  title          TEXT NOT NULL,
  source_ref     TEXT NOT NULL,
  media_type     TEXT NOT NULL,
  bytes_len      INTEGER NOT NULL,
  sha256         TEXT NOT NULL,
  parser_id      TEXT NOT NULL,
  parser_version TEXT NOT NULL,
  schema_version INTEGER NOT NULL,
  truncated      BOOLEAN NOT NULL,
  warnings       TEXT[] NOT NULL,
  content        BYTEA NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX idx_materials_dedupe ON materials(project_id, sha256);
CREATE INDEX idx_materials_project ON materials(project_id, created_at);

CREATE TABLE material_chunks (
  chunk_id     TEXT PRIMARY KEY,
  material_id  TEXT NOT NULL REFERENCES materials(material_id) ON DELETE CASCADE,
  owner_id     TEXT,
  ordinal      INTEGER NOT NULL,
  text         TEXT NOT NULL,
  heading_path TEXT[] NOT NULL,
  anchor       TEXT NOT NULL,
  tokens       TEXT NOT NULL,
  search_tsv   TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', tokens)) STORED NOT NULL,
  embedding    vector(512)
);
CREATE INDEX idx_material_chunks_material ON material_chunks(material_id, ordinal);
CREATE INDEX idx_material_chunks_search_tsv ON material_chunks USING gin (search_tsv);
CREATE INDEX idx_material_chunks_embedding
  ON material_chunks USING hnsw (embedding vector_cosine_ops);

CREATE TABLE explorations (
  exploration_id   TEXT PRIMARY KEY,
  project_id       TEXT NOT NULL,
  owner_id         TEXT,
  kind             TEXT NOT NULL,
  status           TEXT NOT NULL,
  payload          JSONB NOT NULL,
  created_at       TIMESTAMPTZ NOT NULL,
  updated_at       TIMESTAMPTZ NOT NULL,
  lease_owner      TEXT,
  lease_expires_at BIGINT,
  lease_token      INTEGER NOT NULL DEFAULT 0,
  seq              BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_explorations_project ON explorations(project_id, created_at);
CREATE UNIQUE INDEX idx_explorations_running
  ON explorations(project_id) WHERE status = 'running';

CREATE TABLE discussions (
  discussion_id TEXT PRIMARY KEY,
  project_id    TEXT NOT NULL,
  owner_id      TEXT,
  status        TEXT NOT NULL,
  payload       JSONB NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL,
  updated_at    TIMESTAMPTZ NOT NULL,
  seq           BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_discussions_project ON discussions(project_id, created_at);

CREATE TABLE project_memory (
  project_id TEXT PRIMARY KEY,
  owner_id   TEXT,
  payload    JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE model_calls (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id    TEXT,
  purpose     TEXT NOT NULL,
  model       TEXT NOT NULL,
  prompt_sha  TEXT NOT NULL,
  prompt_text TEXT NOT NULL,
  reply_text  TEXT NOT NULL,
  usage_json  JSONB NOT NULL,
  duration_ms INTEGER NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL,
  attempt     INTEGER NOT NULL DEFAULT 1,
  ok          BOOLEAN NOT NULL DEFAULT true,
  error       TEXT
);
CREATE INDEX idx_model_calls_round ON model_calls(round_id, id);

CREATE TABLE tool_calls (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id    TEXT,
  tool_id     TEXT NOT NULL,
  arguments   JSONB NOT NULL,
  result_note TEXT NOT NULL,
  duration_ms INTEGER NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL,
  ok          BOOLEAN NOT NULL DEFAULT true,
  error       TEXT,
  error_kind  TEXT
);
CREATE INDEX idx_tool_calls_round ON tool_calls(round_id, id);

CREATE TABLE observations (
  id         TEXT PRIMARY KEY,
  project_id TEXT NOT NULL,
  owner_id   TEXT,
  round_id   TEXT NOT NULL,
  obs_type   TEXT NOT NULL,
  title      TEXT NOT NULL,
  detail     TEXT NOT NULL DEFAULT '',
  source_ref TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT '',
  seq        BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_observations_project ON observations(project_id, id);
CREATE INDEX idx_observations_round ON observations(round_id);

CREATE TABLE round_digests (
  id         TEXT PRIMARY KEY,
  project_id TEXT NOT NULL,
  owner_id   TEXT,
  round_id   TEXT NOT NULL,
  summary    TEXT NOT NULL,
  sections   TEXT[] NOT NULL DEFAULT '{}',
  features   TEXT[] NOT NULL DEFAULT '{}',
  outcomes   TEXT[] NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL,
  seq        BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_round_digests_project ON round_digests(project_id, id);

CREATE TABLE users (
  user_id       TEXT PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  status        TEXT NOT NULL DEFAULT 'pending',
  role          TEXT NOT NULL DEFAULT 'user',
  approved_by   TEXT,
  approved_at   TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL,
  seq           BIGINT GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE sessions (
  session_id   TEXT PRIMARY KEY,
  user_id      TEXT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  token_hash   TEXT NOT NULL,
  expires_at   TIMESTAMPTZ NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL,
  last_seen_at TIMESTAMPTZ NOT NULL,
  ip           TEXT NOT NULL DEFAULT '',
  user_agent   TEXT NOT NULL DEFAULT '',
  revoked_at   TIMESTAMPTZ
);
CREATE INDEX idx_sessions_user ON sessions(user_id, expires_at);

CREATE TABLE inspirations (
  id         TEXT PRIMARY KEY,
  project_id TEXT NOT NULL,
  owner_id   TEXT,
  origin     TEXT NOT NULL,
  statement  TEXT NOT NULL,
  created_at TEXT NOT NULL,
  seq        BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_inspirations_project ON inspirations(project_id, id);

CREATE TABLE vector_index_meta (
  id         SMALLINT PRIMARY KEY CHECK (id = 1),
  profile    TEXT NOT NULL,
  dimensions INTEGER NOT NULL,
  model      TEXT NOT NULL
);

CREATE INDEX idx_documents_owner ON documents(owner_id);
CREATE INDEX idx_document_versions_owner ON document_versions(owner_id, project_id);
CREATE INDEX idx_rounds_owner ON rounds(owner_id, project_id, created_at);
CREATE INDEX idx_evidence_ledgers_owner ON evidence_ledgers(owner_id);
CREATE INDEX idx_materials_owner ON materials(owner_id, project_id);
CREATE INDEX idx_material_chunks_owner ON material_chunks(owner_id, material_id);
CREATE INDEX idx_explorations_owner ON explorations(owner_id, project_id, created_at);
CREATE INDEX idx_discussions_owner ON discussions(owner_id, project_id, created_at);
CREATE INDEX idx_project_memory_owner ON project_memory(owner_id);
CREATE INDEX idx_observations_owner ON observations(owner_id, project_id);
CREATE INDEX idx_round_digests_owner ON round_digests(owner_id, project_id);
CREATE INDEX idx_inspirations_owner ON inspirations(owner_id, project_id);
CREATE INDEX idx_templates_owner ON templates(owner_id);
